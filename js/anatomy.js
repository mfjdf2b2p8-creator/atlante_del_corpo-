  function bbox(pts) {
    let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
    pts.forEach(([x, y]) => { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); });
    return [x0, y0, x1, y1];
  }

  function fiberLines(pts, o, side, W) {
    const out = [];
    const [x0, y0, x1, y1] = bbox(pts);
    if (o.fan) {
      let O = side === "l" ? [400 - o.fan[0], o.fan[1]] : o.fan.slice();
      O = W([O])[0];
      // campiona il contorno
      for (let i = 0; i < pts.length; i++) {
        const a = pts[i], b = pts[(i + 1) % pts.length];
        const len = Math.hypot(b[0] - a[0], b[1] - a[1]);
        const n = Math.max(1, Math.round(len / 3.4));
        for (let k = 0; k < n; k++) {
          const t = k / n, px = a[0] + (b[0] - a[0]) * t, py = a[1] + (b[1] - a[1]) * t;
          out.push(`M${G.f(O[0])},${G.f(O[1])}L${G.f(px + (px - O[0]) * .15)},${G.f(py + (py - O[1]) * .15)}`);
        }
      }
    } else {
      let [dx, dy] = o.fd || [0, 1];
      if (side === "l") dx = -dx;
      const L = Math.hypot(dx, dy); dx /= L; dy /= L;
      const nx = -dy, ny = dx;
      const cx = (x0 + x1) / 2, cy = (y0 + y1) / 2, R = Math.hypot(x1 - x0, y1 - y0) / 2 + 2;
      for (let s = -R; s <= R; s += 3) {
        const px = cx + nx * s, py = cy + ny * s;
        out.push(`M${G.f(px - dx * R)},${G.f(py - dy * R)}L${G.f(px + dx * R)},${G.f(py + dy * R)}`);
      }
    }
    return out.join("");
  }

